/**
 * Picks the axis for a task written in the minutes, by key words
 * (used when the AI did not already propose an axis for that task).
 */
const RULES: [number, RegExp][] = [
  [7, /جائز|جوائز|حفل|تتويج|شهاد|تكريم|رسائل الشكر|شكر|פרס|טקס|תעוד|הוקרה|תודה/],
  [6, /كاتب|كاتبة|قصص|قصة|أدب|סופר|סיפור|ספרות/],
  [4, /مدرب|مدرّب|تدريب|إرشاد|ارشاد|מנח|הדרכ|השתלמ/],
  [5, /موضوع|مواضيع|مئشار|معيار|تقييم|تحكيم|حكام|لجنة التحكيم|مضامين|نصوص|מחוון|שיפוט|נושא|הערכה/],
  [3, /طاقم|الطاقم|فريق|اجتماع اللجنة|צוות/],
  [2, /مدرس|مدارس|مدير|مديرين|معلم|منشور|بوستر|ستاند|إعلان|اعلان|بית ספר|בתי ספר|מנהל|פרסום|פוסטר/],
  [1, /مكان|قاعة|مواصلات|سفر|حافل|تضييف|ضيافة|طعام|ميزانية|شراء|طباعة|מקום|אולם|הסע|כיבוד|תקציב/],
];
export function guessAxis(title: string): number {
  for (const [axis, re] of RULES) if (re.test(title)) return axis;
  return 8; // other tasks
}
